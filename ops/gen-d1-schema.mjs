#!/usr/bin/env node
// Generate a D1-applyable .sql from the SCHEMA const in packages/data/src/schema.ts.
//
// Why this exists: schema.ts is the single source of truth (node:sqlite applies it
// verbatim locally), but D1's `wrangler d1 execute --file` rejects the connection-level
// PRAGMAs at the top of SCHEMA (journal_mode/synchronous/foreign_keys — D1 manages
// those itself). This emits the CREATE statements only, so the same DDL ports to D1.
//
// Usage:
//   node ops/gen-d1-schema.mjs            # write SQL to stdout
//   node ops/gen-d1-schema.mjs out.sql    # write SQL to a file
// Used by `ops/run.sh <env> provision-schema`. No committed .sql artifact (avoids
// drift) — always generated from schema.ts on demand.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = resolve(here, "../packages/data/src/schema.ts");

const src = readFileSync(schemaPath, "utf8");

// SCHEMA is a no-interpolation template literal, so the first backtick after
// `SCHEMA = ` closes it (the DDL itself contains no backticks).
const match = src.match(/export const SCHEMA\s*=\s*`([\s\S]*?)`/);
if (!match) {
  console.error(`gen-d1-schema: could not find 'export const SCHEMA = \`...\`' in ${schemaPath}`);
  process.exit(1);
}

const ddl = match[1]
  .split("\n")
  .filter((line) => !/^\s*PRAGMA\b/i.test(line)) // D1 rejects connection PRAGMAs
  .join("\n")
  .trim();

const header =
  "-- GENERATED by ops/gen-d1-schema.mjs from packages/data/src/schema.ts (PRAGMAs stripped).\n" +
  "-- Do not edit by hand; regenerate. Apply with: ops/run.sh <env> provision-schema\n\n";
const out = `${header}${ddl}\n`;

const target = process.argv[2];
if (target) {
  writeFileSync(target, out);
  console.error(`gen-d1-schema: wrote ${target}`);
} else {
  process.stdout.write(out);
}
